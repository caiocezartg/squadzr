import type { ChatMessageView } from '@domain/entities/chat-message.entity'
import type { IChatMessageRepository } from '@domain/repositories/chat-message.repository'
import type { IRoomRepository } from '@domain/repositories/room.repository'
import type { IRoomMemberRepository } from '@domain/repositories/room-member.repository'
import type { Clock } from '@domain/services/clock.interface'
import { ChatMessageIdConflictError, NotRoomMemberError } from '@application/errors'
import { resolveAccessibleRoom } from '../room/helpers/resolve-accessible-room'

export interface SendChatMessageInput {
  readonly code: string
  readonly authorId: string
  /** Generated by the client, so a retry of one send is idempotent. */
  readonly id: string
  readonly body: string
}

export interface SendChatMessageOutput {
  readonly roomCode: string
  readonly message: ChatMessageView
  /** False when the id was already stored by this author: the message is the stored one. */
  readonly created: boolean
}

export interface ISendChatMessageUseCase {
  execute(input: SendChatMessageInput): Promise<SendChatMessageOutput>
}

export class SendChatMessageUseCase implements ISendChatMessageUseCase {
  constructor(
    private readonly chatMessageRepository: IChatMessageRepository,
    private readonly roomRepository: IRoomRepository,
    private readonly roomMemberRepository: IRoomMemberRepository,
    private readonly clock: Clock
  ) {}

  async execute(input: SendChatMessageInput): Promise<SendChatMessageOutput> {
    const { room } = await resolveAccessibleRoom(
      this.roomRepository,
      this.roomMemberRepository,
      this.clock,
      { code: input.code, viewerId: input.authorId }
    )

    const outcome = await this.chatMessageRepository.createWithinRate({
      id: input.id,
      roomId: room.id,
      authorId: input.authorId,
      body: input.body,
      createdAt: this.clock.now(),
    })

    switch (outcome.kind) {
      case 'created':
        return { roomCode: room.code, message: outcome.message, created: true }
      case 'duplicate':
        return { roomCode: room.code, message: outcome.message, created: false }
      case 'not_member':
        throw new NotRoomMemberError(input.authorId, room.id)
      case 'id_conflict':
        throw new ChatMessageIdConflictError(input.id)
    }
  }
}
